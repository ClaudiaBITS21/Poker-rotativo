await t('nadie lee el hash',getDoc(doc(X,'pins','pA')),false);
await t('se ve el candado',getDoc(doc(X,'pinflags','pA')),true);
await t('sesión con PIN incorrecto',setDoc(doc(X,'sessions','uX'),{pid:'pA',h:sha('pA:0000')}),false);
await t('sesión con PIN correcto',setDoc(doc(A,'sessions','uA'),{pid:'pA',h:sha('pA:1234')}),true);
await t('no puede crear sesión de otro uid',setDoc(doc(X,'sessions','uA'),{pid:'pA',h:sha('pA:1234')}),false);
await t('A cambia su asistencia',updateDoc(doc(A,'games','g'),{'parts.pA.st':'come',_p:'pA'}),true);
await t('A NO cambia la de B',updateDoc(doc(A,'games','g'),{'parts.pB.st':'no',_p:'pB'}),false);
await t('A suma rebuy a B (partida la maneja cualquiera)',updateDoc(doc(A,'games','g'),{'parts.pB.rb':2,_p:'pB'}),true);
await t('sin PIN no cambia asistencia',updateDoc(doc(X,'games','g'),{'parts.pA.st':'no',_p:'pA'}),false);
await t('sin PIN maneja reloj',updateDoc(doc(X,'games','g'),{'timer.running':true,'timer.level':1}),true);
await t('sin PIN elimina a B',updateDoc(doc(X,'games','g'),{'parts.pB.ko':123,'result.p1':'',_p:'pB'}),true);
await t('no toca dos jugadores a la vez',updateDoc(doc(X,'games','g'),{'parts.pA.rb':1,'parts.pB.rb':3,_p:'pA'}),false);
await t('crear partida vacía',setDoc(doc(X,'games','g2'),{type:'mie',status:'open',parts:{},result:{}}),true);
await t('crear partida con anotados',setDoc(doc(X,'games','g3'),{type:'mie',status:'open',parts:{pB:{st:'no'}}}),false);
await t('anónimo no borra partidas',deleteDoc(doc(X,'games','g2')),false);
await t('anónimo edita jugador',updateDoc(doc(X,'players','pB'),{hand:'K9'}),true);
await t('anónimo no borra jugador',deleteDoc(doc(X,'players','pB')),false);
await t('anónimo no resetea PIN',deleteDoc(doc(X,'pins','pA')),false);
await t('Firu crea su PIN',newPin(F,'pmuhuxmb6f8rh','4321'),true);
await t('Firu entra',setDoc(doc(F,'sessions','uF'),{pid:'pmuhuxmb6f8rh',h:sha('pmuhuxmb6f8rh:4321')}),true);
await t('Firu cambia asistencia de B',updateDoc(doc(F,'games','g'),{'parts.pB.st':'no',_p:'pB'}),true);
