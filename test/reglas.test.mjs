import {initializeTestEnvironment,assertSucceeds,assertFails} from '@firebase/rules-unit-testing';
import {doc,getDoc,setDoc,updateDoc,deleteDoc,writeBatch} from 'firebase/firestore';
import fs from 'fs';import crypto from 'crypto';
const sha=t=>crypto.createHash('sha256').update(t).digest('hex');
const env=await initializeTestEnvironment({projectId:'poker-rotativo',firestore:{rules:fs.readFileSync(new URL('../firestore.rules',import.meta.url),'utf8'),host:'127.0.0.1',port:8085}});
await env.withSecurityRulesDisabled(async c=>{const d=c.firestore();
  for(const id of ['pA','pB','pmuhuxmb6f8rh']) await setDoc(doc(d,'players',id),{name:id,active:true});
  await setDoc(doc(d,'games','g'),{type:'vie',status:'open',parts:{pA:{st:'juega'},pB:{st:'juega',rb:1}},timer:{running:false,level:0},result:{}});
});
const anon=uid=>env.authenticatedContext(uid,{firebase:{sign_in_provider:'anonymous'}}).firestore();
const google=(uid,email)=>env.authenticatedContext(uid,{email,email_verified:true}).firestore();
const nobody=env.unauthenticatedContext().firestore();
let ok=0,bad=0;const t=async(name,p,expect)=>{try{await (expect?assertSucceeds(p):assertFails(p));ok++;console.log('✓',name)}catch(e){bad++;console.log('✗',name,e.message.slice(0,160))}};
const A=anon('uA'),B=anon('uB'),X=anon('uX'),F=anon('uF'),G=google('uG','claudia@rodo.es'),O=google('uO','otro@gmail.com');
const newPin=(db,pid,pin)=>{const b=writeBatch(db);b.set(doc(db,'pins',pid),{h:sha(pid+':'+pin)});b.set(doc(db,'pinflags',pid),{at:1});return b.commit()};
